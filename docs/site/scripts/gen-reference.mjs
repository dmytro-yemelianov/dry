fs.mkdirSync(generatedDir, { recursive: true });

function repoPath(relativePath) {
  return path.join(repoRoot, relativePath);
}

function read(relativePath) {
  return fs.readFileSync(repoPath(relativePath), 'utf8');
}

function readJson(relativePath) {
  return JSON.parse(read(relativePath));
}

function exists(relativePath) {
  return fs.existsSync(repoPath(relativePath));
}

function hash(relativePath) {
  if (!exists(relativePath)) return null;
  return createHash('sha256').update(read(relativePath)).digest('hex');
}

function hashText(text) {
  return createHash('sha256').update(text).digest('hex');
}

function writeGenerated(name, text) {
  fs.writeFileSync(path.join(generatedDir, name), text, 'utf8');
}

function cleanComment(raw) {
  if (!raw) return '';
  return raw
    .replace(/^\/\*\*/, '')
    .replace(/\*\/$/, '')
    .split('\n')
    .map((line) => line.replace(/^\s*\* ?/, '').trimEnd())
    .join('\n')
    .trim();
}

function firstSentence(text) {
  return (text || 'Declared in the public API.').split('\n').find(Boolean) || 'Declared in the public API.';
}

function escapeMarkdownInline(text) {
  return String(text).replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '\\|');
}

function fenced(language, text) {
  return ['```' + language, text.trimEnd(), '```'].join('\n');
}

function banner() {
  return '<!-- Generated by docs/site/scripts/gen-reference.mjs. Do not edit by hand. -->\n';
}

function sourceFileFor(relativePath) {
  return ts.createSourceFile(relativePath, read(relativePath), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
}

function hasExportModifier(node) {
  return Boolean(node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword));
}

function docFor(node, sourceFile) {
  const ranges = ts.getLeadingCommentRanges(sourceFile.text, node.pos) || [];
  for (const range of ranges.slice().reverse()) {
    const comment = sourceFile.text.slice(range.pos, range.end);
    if (comment.startsWith('/**')) return cleanComment(comment);
  }
  const full = node.getFullText(sourceFile);
  const match = full.match(/\/\*\*[\s\S]*?\*\//);
  return match ? cleanComment(match[0]) : '';
}

function typeText(node, sourceFile) {
  if (!node) return '';
  return node.getText(sourceFile).replace(/\s+/g, ' ').trim();
}

function nameText(node) {
  if (!node) return '';
  if (ts.isIdentifier(node) || ts.isStringLiteral(node) || ts.isNumericLiteral(node)) return node.text;
  return node.getText();
}

function paramInfo(param, sourceFile) {
  return {
    name: nameText(param.name),
    type: typeText(param.type, sourceFile) || 'any',
    optional: Boolean(param.questionToken || param.initializer),
    default: param.initializer ? param.initializer.getText(sourceFile) : '',
  };
}

function signatureForDeclaration(decl, sourceFile, name) {
  if (ts.isFunctionDeclaration(decl)) {
    const params = decl.parameters.map((param) => param.getText(sourceFile)).join(', ');
    const returns = decl.type ? `: ${decl.type.getText(sourceFile)}` : '';
    return `export function ${name}(${params})${returns}`;
  }
  if (ts.isClassDeclaration(decl)) return `export class ${name}`;
  if (ts.isInterfaceDeclaration(decl)) return `export interface ${name}`;
  if (ts.isTypeAliasDeclaration(decl)) return `export type ${name} = ${decl.type.getText(sourceFile)}`;
  if (ts.isVariableDeclaration(decl)) {
    const type = decl.type ? `: ${decl.type.getText(sourceFile)}` : '';
    return `export const ${name}${type}`;
  }
  return `export ${name}`;
}

function interfaceFields(decl, sourceFile) {
  return decl.members
    .filter(ts.isPropertySignature)
    .map((member) => ({
      name: nameText(member.name),
      optional: Boolean(member.questionToken),
      type: typeText(member.type, sourceFile) || 'any',
      summary: firstSentence(docFor(member, sourceFile)),
    }));
}

function classMethods(decl, sourceFile) {
  return decl.members
    .filter(ts.isMethodDeclaration)
    .filter((member) => !member.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.PrivateKeyword))
    .map((member) => {
      const name = nameText(member.name);
      const params = member.parameters.map((param) => paramInfo(param, sourceFile));
      const returns = typeText(member.type, sourceFile) || 'void';
      return {
        name,
        signature: `${name}(${member.parameters.map((param) => param.getText(sourceFile)).join(', ')}): ${returns}`,
        summary: firstSentence(docFor(member, sourceFile)),
        params,
        returns,
      };
    });
}

function declarationToDoc(exp, decl, sourceFile, docNode = decl) {
  const name = exp.name;
  let kind = exp.isTypeOnly ? 'type' : 'value';
  if (ts.isClassDeclaration(decl)) kind = 'class';
  if (ts.isInterfaceDeclaration(decl)) kind = 'interface';
  if (ts.isTypeAliasDeclaration(decl)) kind = 'type';
  if (ts.isFunctionDeclaration(decl)) kind = 'function';
  if (ts.isVariableDeclaration(decl)) kind = 'const';

  const doc = docFor(docNode, sourceFile);
  const out = {
    ...exp,
    kind,
    summary: firstSentence(doc),
    doc,
    signature: signatureForDeclaration(decl, sourceFile, name),
    fields: [],
    params: [],
    returns: '',
    methods: [],
  };

  if (ts.isInterfaceDeclaration(decl)) out.fields = interfaceFields(decl, sourceFile);
  if (ts.isFunctionDeclaration(decl)) {
    out.params = decl.parameters.map((param) => paramInfo(param, sourceFile));
    out.returns = typeText(decl.type, sourceFile) || 'void';
  }
  if (ts.isClassDeclaration(decl)) out.methods = classMethods(decl, sourceFile);
  return out;
}

function parseTsExports() {
  const indexSource = read(sourceFiles.tsIndex);
  const exports = [];
  const groupRe = /export\s+(type\s+)?\{([\s\S]*?)\}\s+from\s+['"](.+?)['"]/g;
  let match;
  while ((match = groupRe.exec(indexSource))) {
    const isTypeOnly = Boolean(match[1]);
    const moduleRef = match[3];
    const modulePath = path.posix.join('sdk/ts/src', `${moduleRef.replace(/^\.\//, '')}.ts`);
    const names = match[2]
      .split(',')
      .map((item) => item.trim())
      .filter(Boolean)
      .map((item) => item.replace(/\s+as\s+.+$/, '').trim());

    for (const name of names) exports.push({ name, modulePath, isTypeOnly });
  }
  return exports.sort((a, b) => a.name.localeCompare(b.name));
}

function findTsDeclaration(exp) {
  if (!exists(exp.modulePath)) {
    return { ...exp, kind: exp.isTypeOnly ? 'type' : 'value', summary: 'Source file not found.', signature: '', fields: [], params: [], methods: [] };
  }

  const sourceFile = sourceFileFor(exp.modulePath);
  for (const statement of sourceFile.statements) {
    if (ts.isVariableStatement(statement) && hasExportModifier(statement)) {
      for (const decl of statement.declarationList.declarations) {
        if (nameText(decl.name) === exp.name) return declarationToDoc(exp, decl, sourceFile, statement);
      }
    }
    if (!hasExportModifier(statement)) continue;
    if ('name' in statement && statement.name && nameText(statement.name) === exp.name) {
      return declarationToDoc(exp, statement, sourceFile);
    }
  }

  return {
    ...exp,
    kind: exp.isTypeOnly ? 'type' : 'value',
    summary: 'No exported declaration found in source file.',
    signature: '',
    fields: [],
    params: [],
    methods: [],
  };
}

function parsePythonApi() {
  const code = String.raw`
import ast
import json
import sys

source = open(sys.argv[1], encoding="utf-8").read()
tree = ast.parse(source)

def unparse(node):
    if node is None:
        return ""
    return ast.unparse(node)

def public_all():
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "__all__":
                    return [elt.value for elt in node.value.elts if isinstance(elt, ast.Constant)]
    return []

def params(fn):
    out = []
    positional = list(fn.args.posonlyargs) + list(fn.args.args)
    defaults = [None] * (len(positional) - len(fn.args.defaults)) + list(fn.args.defaults)
    for arg, default in zip(positional, defaults):
        out.append({
            "name": arg.arg,
            "annotation": unparse(arg.annotation),
            "default": unparse(default),
            "optional": default is not None,
        })
    if fn.args.vararg:
        out.append({"name": "*" + fn.args.vararg.arg, "annotation": unparse(fn.args.vararg.annotation), "default": "", "optional": False})
    if fn.args.kwonlyargs:
        if not fn.args.vararg:
            out.append({"name": "*", "annotation": "", "default": "", "optional": False})
        for arg, default in zip(fn.args.kwonlyargs, fn.args.kw_defaults):
            out.append({"name": arg.arg, "annotation": unparse(arg.annotation), "default": unparse(default), "optional": default is not None})
    if fn.args.kwarg:
        out.append({"name": "**" + fn.args.kwarg.arg, "annotation": unparse(fn.args.kwarg.annotation), "default": "", "optional": False})
    return out

def signature(fn):
    parts = []
    for item in params(fn):
        text = item["name"]
        if item["annotation"]:
            text += ": " + item["annotation"]
        if item["default"]:
            text += " = " + item["default"]
        parts.append(text)
    result = "def " + fn.name + "(" + ", ".join(parts) + ")"
    if fn.returns is not None:
        result += " -> " + unparse(fn.returns)
    return result

def fn_info(fn):
    return {
        "name": fn.name,
        "signature": signature(fn),
        "doc": ast.get_docstring(fn) or "",
        "params": params(fn),
        "returns": unparse(fn.returns),
    }

assignments = {}
classes = []
functions = []

for node in tree.body:
    if isinstance(node, ast.Assign):
        for target in node.targets:
            if isinstance(target, ast.Name):
                assignments[target.id] = unparse(node.value)
    elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        assignments[node.target.id] = unparse(node.annotation)
    elif isinstance(node, ast.ClassDef):
        classes.append({
            "name": node.name,
            "doc": ast.get_docstring(node) or "",
            "methods": [fn_info(item) for item in node.body if isinstance(item, ast.FunctionDef) and not item.name.startswith("_")],
        })
    elif isinstance(node, ast.FunctionDef):
        functions.append(fn_info(node))

print(json.dumps({"all": public_all(), "assignments": assignments, "classes": classes, "functions": functions}))
`;

  const pythonPath = repoPath(sourceFiles.pythonSdk);
  const bins = ['python3', 'python'];
  for (const bin of bins) {
    try {
      return JSON.parse(execFileSync(bin, ['-', pythonPath], { input: code, encoding: 'utf8' }));
    } catch {
      // Try the next Python binary.
    }
  }
  throw new Error('Unable to run python3 or python for Python API extraction');
}

function extractHeadings(relativePath) {
  if (!exists(relativePath)) return [];
  const headings = [];
  let inFence = false;
  for (const line of read(relativePath).split('\n')) {
    if (/^```/.test(line.trim())) {
      inFence = !inFence;
      continue;
    }
    if (inFence || !/^#{1,3} /.test(line)) continue;
    headings.push(line);
  }
  return headings.map((line) => {
    const level = line.match(/^#+/)[0].length;
    const text = line.replace(/^#+\s+/, '').trim();
    return { level, text };
  });
}

function renderHeadingIndex(title, sourcePath, intro) {
  const headings = extractHeadings(sourcePath);
  const lines = [banner(), `# ${title}`, '', intro, '', `Source: \`${sourcePath}\``, ''];
  if (headings.length) {
    lines.push('## Source sections', '');
    for (const heading of headings) {
      const indent = '  '.repeat(Math.max(0, heading.level - 1));
      lines.push(`${indent}- ${escapeMarkdownInline(heading.text)}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function extractMarkedSection(relativePath, marker) {
  if (!exists(relativePath)) return '';
  const source = read(relativePath);
  const start = `<!-- docs-gen:start ${marker} -->`;
  const end = `<!-- docs-gen:end ${marker} -->`;
  const startIndex = source.indexOf(start);
  const endIndex = source.indexOf(end);
  if (startIndex === -1 || endIndex === -1 || endIndex <= startIndex) return '';
  return source.slice(startIndex + start.length, endIndex).trim();
}

function sanitizeExtractedMarkdown(markdown) {
  return markdown.replace(/\[([^\]]+)\]\((?!https?:|#)([^)]+)\)/g, (_match, label, target) => {
    return `${label} (\`${target}\`)`;
  });
}

function renderMarkedReference(title, intro, sections) {
  const lines = [banner(), `# ${title}`, '', intro, ''];
  for (const section of sections) {
    const content = extractMarkedSection(section.source, section.marker);
    lines.push(`Source: \`${section.source}\``, '');
    if (content) {
      lines.push(sanitizeExtractedMarkdown(content), '');
    } else {
      lines.push(`Marked section \`${section.marker}\` was not found.`, '');
    }
  }
  return lines.join('\n');
}

function renderParamTable(params, typeLabel = 'Type') {
  const visible = params.filter((param) => param.name !== 'self' && param.name !== '*');
  if (!visible.length) return '';
  const lines = ['', '| Parameter | ' + typeLabel + ' | Default | Required |', '| --- | --- | --- | --- |'];
  for (const param of visible) {
    const type = param.type || param.annotation || 'any';
    const defaultValue = param.default || '';
    const required = param.optional ? 'No' : 'Yes';
    lines.push(`| \`${escapeMarkdownInline(param.name)}\` | \`${escapeMarkdownInline(type)}\` | ${defaultValue ? `\`${escapeMarkdownInline(defaultValue)}\`` : ''} | ${required} |`);
  }
  lines.push('');
  return lines.join('\n');
}

function renderFieldTable(fields) {
  if (!fields?.length) return '';
  const lines = ['', '### Fields', '', '| Field | Type | Required | Summary |', '| --- | --- | --- | --- |'];
  for (const field of fields) {
    lines.push(`| \`${escapeMarkdownInline(field.name)}\` | \`${escapeMarkdownInline(field.type)}\` | ${field.optional ? 'No' : 'Yes'} | ${escapeMarkdownInline(field.summary)} |`);
  }
  lines.push('');
  return lines.join('\n');
}

function renderTsReference(exports) {
  const declarations = exports.map(findTsDeclaration);
  const lines = [
    banner(),
    '# TypeScript SDK',
    '',
    `Generated from \`${sourceFiles.tsIndex}\` and public re-export sources using the TypeScript compiler API.`,
    '',
    '## Public exports',
    '',
    '| Export | Kind | Source | Summary |',
    '| --- | --- | --- | --- |',
  ];

  for (const item of declarations) {
    lines.push(`| \`${item.name}\` | ${item.kind} | \`${item.modulePath}\` | ${escapeMarkdownInline(item.summary)} |`);
  }

  for (const item of declarations) {
    lines.push('', `## \`${item.name}\``, '', `Source: \`${item.modulePath}\``, '');
    if (item.signature) lines.push(fenced('ts', item.signature), '');
    lines.push(item.doc || item.summary, '');
    const fields = renderFieldTable(item.fields);
    if (fields) lines.push(fields);
    const params = renderParamTable(item.params);
    if (params) lines.push('### Parameters', params, `Returns: \`${escapeMarkdownInline(item.returns || 'void')}\``, '');
    if (item.methods?.length) {
      lines.push('### Methods', '', '| Method | Signature | Summary |', '| --- | --- | --- |');
      for (const method of item.methods) {
        lines.push(`| \`${method.name}\` | \`${escapeMarkdownInline(method.signature)}\` | ${escapeMarkdownInline(method.summary)} |`);
      }
      lines.push('', '### Method details', '');
      for (const method of item.methods) {
        lines.push(`#### \`${method.name}\``, '', fenced('ts', method.signature), '');
        const methodParams = renderParamTable(method.params);
        if (methodParams) lines.push(methodParams);
        lines.push(`Returns: \`${escapeMarkdownInline(method.returns)}\``, '', method.summary, '');
      }
    }
  }

  return lines.join('\n');
}

function renderPythonReference(api) {
  const classMap = new Map(api.classes.map((item) => [item.name, item]));
  const functionMap = new Map(api.functions.map((item) => [item.name, item]));
  const lines = [
    banner(),
    '# Python SDK',
    '',
    `Generated from \`${sourceFiles.pythonSdk}\` using Python AST extraction.`,
    '',
    '## Public names',
    '',
    '| Name | Kind | Summary |',
    '| --- | --- | --- |',
  ];

  for (const name of api.all) {
    let kind = 'value';
    let summary = '';
    if (classMap.has(name)) {
      kind = 'class';
      summary = firstSentence(classMap.get(name).doc);
    } else if (functionMap.has(name)) {
      kind = 'function';
      summary = firstSentence(functionMap.get(name).doc);
    } else if (api.assignments[name]) {
      kind = new Set(['PRINTERS', 'TPMS_SURFACES']).has(name) ? 'constant' : 'type alias';
      summary = `\`${api.assignments[name]}\``;
    }
    lines.push(`| \`${name}\` | ${kind} | ${escapeMarkdownInline(summary || 'Declared in the public API.')} |`);
  }

  for (const klass of api.classes.filter((item) => api.all.includes(item.name))) {
    lines.push('', `## \`${klass.name}\``, '', klass.doc || 'Declared in the public API.', '', '### Methods', '');
    lines.push('| Method | Signature | Summary |', '| --- | --- | --- |');
    for (const method of klass.methods) {
      lines.push(`| \`${method.name}\` | \`${escapeMarkdownInline(method.signature)}\` | ${escapeMarkdownInline(firstSentence(method.doc))} |`);
    }
    lines.push('', '### Method details', '');
    for (const method of klass.methods) {
      lines.push(`#### \`${method.name}\``, '', fenced('py', method.signature), '');
      const params = renderParamTable(method.params, 'Annotation');
      if (params) lines.push(params);
      lines.push(`Returns: \`${escapeMarkdownInline(method.returns || 'None')}\``, '', method.doc || 'Declared in the public API.', '');
    }
  }

  for (const fn of api.functions.filter((item) => api.all.includes(item.name))) {
    lines.push('', `## \`${fn.name}\``, '', fenced('py', fn.signature), '');
    const params = renderParamTable(fn.params, 'Annotation');
    if (params) lines.push(params);
    lines.push(`Returns: \`${escapeMarkdownInline(fn.returns || 'None')}\``, '', fn.doc || 'Declared in the public API.', '');
  }

  return lines.join('\n');
}

function runCliHelp(args = []) {
  try {
    return execFileSync('cargo', ['run', '-q', '-p', 'dry-cli', '--', ...args], {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
  } catch {
    return null;
  }
}

function parseCliCommands(helpText) {
  const commands = [];
  let inCommands = false;
  for (const line of helpText.split('\n')) {
    if (/^Commands:/.test(line)) {
      inCommands = true;
      continue;
    }
    if (inCommands && /^Options:/.test(line)) break;
    if (!inCommands) continue;
    const match = line.match(/^\s{2}([a-z][a-z0-9-]*)\s+(.*)$/);
    if (match && match[1] !== 'help') commands.push({ name: match[1], summary: match[2].trim() });
  }
  return commands;
}

function renderCliReference() {
  const rootHelp = runCliHelp(['--help']);
  if (!rootHelp) {
    return {
      text: renderHeadingIndex('CLI', sourceFiles.cliCookbook, 'Generated index of command-line documentation source sections. CLI execution was unavailable, so this page fell back to the checked-in cookbook.'),
      helpHash: null,
    };
  }

  const commands = parseCliCommands(rootHelp);
  const commandHelps = [];
  for (const command of commands) {
    commandHelps.push({ ...command, help: runCliHelp([command.name, '--help']) || '' });
  }

  const lines = [
    banner(),
    '# CLI',
    '',
    'Generated from actual CLI help output.',
    '',
    'Command: `cargo run -q -p dry-cli -- --help`',
    '',
    '## Root help',
    '',
    fenced('text', rootHelp),
    '',
    '## Commands',
    '',
    '| Command | Summary |',
    '| --- | --- |',
  ];

  for (const command of commandHelps) {
    lines.push(`| \`${command.name}\` | ${escapeMarkdownInline(command.summary)} |`);
  }

  for (const command of commandHelps) {
    lines.push('', `### \`${command.name}\``, '', command.summary, '');
    if (command.help) lines.push(fenced('text', command.help), '');
  }

  return {
    text: lines.join('\n'),
    helpHash: hashText([rootHelp, ...commandHelps.map((item) => item.help)].join('\n\n')),
  };
}

